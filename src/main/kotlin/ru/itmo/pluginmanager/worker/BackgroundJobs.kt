package ru.itmo.pluginmanager.worker

/** Точки входа планировщика; PostgreSQL, а не память процесса, является источником заданий. */
interface BackgroundJobs {
    /** Захватывает активации в пределах настроенного параллелизма, включая работу после перезапуска. */
    suspend fun activateDue()

    /** Захватывает готовые healthcheck-задания в пределах отдельного лимита параллелизма. */
    suspend fun checkDue()

    /** Удаляет устаревшую историю и допустимые неактивные маршруты ограниченными пачками. */
    suspend fun cleanUp()
}
